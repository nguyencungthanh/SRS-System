"""Wear NFR study (D-71..D-79): python -m optimization.wear -> results/wear.md.

Simulates several "months" of seeded random traffic with the real modules and checks, at the
end of every month, the spread (max - min) / max of the P1-P4 trip counters against
WEAR_MONTH_LIMIT. Three kinds of run:

    balanced      Dispatch's wear balancing on (D-78), the shipped behaviour
    unbalanced    balancing off: Dispatch as it was before the NFR
    maintenance   balanced, and P3 spends month 2 in maintenance (D-75)

A real month is 30 days; simulating one takes hours. The study shortens the month
(--month-hours) and says so in the report. A shorter month is the harder case for a
balancing dispatcher: the totals are smaller while the gap it leaves stays about the same.

    python -m optimization.wear                       # 7 months of 2 h, 2 seeds (~8 min)
    python -m optimization.wear --month-hours 1 --seeds 1     # quick look (~3 min)
"""

from __future__ import annotations

import argparse
import json
import time
from concurrent.futures import ProcessPoolExecutor
from dataclasses import asdict, dataclass, replace
from pathlib import Path
from typing import Any

from contracts.config import (
    DRAIN_S,
    WEAR_CARS,
    WEAR_MAX_PENALTY_S,
    WEAR_MONTH_LIMIT,
    WEAR_PENALTY_S_PER_FLOOR,
    WEAR_RESET_MONTHS,
)
from contracts.enums import DispatchAlgorithm, Role
from contracts.messages import MaintenanceSet, RecoveryRequest

KINDS = ("balanced", "unbalanced", "maintenance")
MAINTAINED_CAR = "P3"


@dataclass(frozen=True)
class WearJob:
    kind: str  # one of KINDS
    seed: int
    months: int
    month_s: float


def run_wear(job: WearJob) -> dict[str, Any]:
    """Simulate one job. Top-level so worker processes can import it."""
    import cabin
    import control_center
    import dispatch
    from scenarios.traffic import random_traffic
    from simulation.engine import Engine, ModuleSet

    gain = None if job.kind == "unbalanced" else WEAR_PENALTY_S_PER_FLOOR
    modules = ModuleSet(
        dispatch=lambda policy: dispatch.create(
            policy, DispatchAlgorithm.COMMITMENT, wear_gain=gain
        ),
        cabin=cabin.create,
        cc=control_center.create,
        kinds={"dispatch": "real", "cabin": "real", "cc": "real"},
    )
    scenario = random_traffic(job.seed, trace_s=job.months * job.month_s)
    inputs = ()
    if job.kind == "maintenance":  # month 2 in maintenance, back for month 3 (D-75)
        inputs = (
            MaintenanceSet(t_sim=job.month_s, car_id=MAINTAINED_CAR, on=True, role=Role.MAINTAINER),
            MaintenanceSet(
                t_sim=2 * job.month_s, car_id=MAINTAINED_CAR, on=False, role=Role.MAINTAINER
            ),
            RecoveryRequest(t_sim=2 * job.month_s, car_id=MAINTAINED_CAR, role=Role.SUPERVISOR),
        )
    scenario = replace(
        scenario,
        name=f"WEAR-{job.kind}-{job.seed}",
        inputs=inputs,
        duration_s=job.months * job.month_s + DRAIN_S,  # D-31: then count unserved
        wear_month_s=job.month_s,
    )
    started = time.perf_counter()
    engine = Engine(modules, scenario, job.seed)
    engine.run_to_end()
    metrics = engine.metrics()
    return {
        "job": asdict(job),
        "months": engine.observer.months,
        "mean_wait": metrics["mean_wait"],
        "p95_wait": metrics["p95_wait"],
        "unserved": metrics["unserved"],
        "calls": engine.observer.calls,
        "wall_s": round(time.perf_counter() - started, 1),
    }


def study(month_s: float, months: int, seeds: tuple[int, ...], workers: int | None) -> list[dict]:
    jobs = [WearJob(kind, s, months, month_s) for kind in KINDS[:2] for s in seeds]
    jobs.append(WearJob("maintenance", seeds[0], months, month_s))
    with ProcessPoolExecutor(workers) as pool:
        return list(pool.map(run_wear, jobs))


def _pct(value: float | None) -> str:
    return "-" if value is None else f"{value * 100:.2f} %"


def _markdown(results: list[dict], month_s: float, months: int, wall_s: float) -> str:
    limit = WEAR_MONTH_LIMIT
    hours = month_s / 3600
    lines = [
        "# Wear leveling (new NFR) - month-end trip counter spread",
        "",
        f"Generated by `python -m optimization.wear` in {wall_s:.0f} s with the real modules.",
        "",
        "## Rule checked (DECISIONS D-71..D-79)",
        "",
        "- Trip counter = floors travelled by each car; compared cars: "
        f"{', '.join(WEAR_CARS)} (G1 left out, D-73).",
        f"- Spread = (max - min) / max at every month end; limit {limit * 100:.0f} % (D-76; "
        "the e-mail asked for 2 %, so the 2 % column is shown too).",
        f"- Counters accumulate and are reset every {WEAR_RESET_MONTHS} months (D-76, D-77).",
        "- A car in maintenance during a month is left out of that month (D-75).",
        f"- Dispatch balancing (D-78): a car's pickup ETA gets {WEAR_PENALTY_S_PER_FLOOR:g} s "
        "per floor it has travelled beyond the least-worn candidate, at most "
        f"{WEAR_MAX_PENALTY_S:g} s.",
        "",
        f"**Months are shortened to {hours:g} h of simulated traffic** (one passenger every "
        "12 s on average). A real month is 30 days. A shorter month is the harder case for "
        "a balancing dispatcher: the totals are smaller while the gap it leaves stays about "
        "the same.",
        "",
        "## Summary",
        "",
        f"| Run | Months | Worst spread | Months over {limit * 100:.0f} % | Months over 2 % "
        "| Mean wait (s) | P95 wait (s) | Unserved |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in results:
        checked = [m for m in r["months"] if m["spread"] is not None]
        worst = max((m["spread"] for m in checked), default=None)
        over = sum(1 for m in checked if m["spread"] > limit + 1e-9)
        over2 = sum(1 for m in checked if m["spread"] > 0.02 + 1e-9)
        j = r["job"]
        lines.append(
            f"| {j['kind']} (seed {j['seed']}) | {len(r['months'])} | {_pct(worst)} | "
            f"{over} | {over2} | {r['mean_wait']:.1f} | {r['p95_wait']:.1f} | "
            f"{r['unserved']}/{r['calls']} |"
        )
    for r in results:
        j = r["job"]
        lines += [
            "",
            f"## {j['kind']}, seed {j['seed']}",
            "",
            "| Month | " + " | ".join(WEAR_CARS) + " | Left out | Spread | Result |",
            "|---|" + "---|" * len(WEAR_CARS) + "---|---|---|",
        ]
        for m in r["months"]:
            reset = " (reset after)" if m["month"] % WEAR_RESET_MONTHS == 0 else ""
            counts = " | ".join(f"{m['counters'].get(c, 0):.0f}" for c in WEAR_CARS)
            verdict = "pass" if m["ok"] else "**fail**"
            lines.append(
                f"| {m['month']}{reset} | {counts} | {', '.join(m['excluded']) or '-'} | "
                f"{_pct(m['spread'])} | {verdict} |"
            )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m optimization.wear", description=__doc__)
    parser.add_argument("--month-hours", type=float, default=2.0, help="length of a month")
    parser.add_argument("--months", type=int, default=WEAR_RESET_MONTHS + 1)
    parser.add_argument("--seeds", type=int, nargs="+", default=[1, 2])
    parser.add_argument("--workers", type=int, default=None)
    parser.add_argument("--out", type=Path, default=Path("results"))
    args = parser.parse_args(argv)
    month_s = args.month_hours * 3600
    started = time.perf_counter()
    results = study(month_s, args.months, tuple(args.seeds), args.workers)
    wall = time.perf_counter() - started
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "wear.md").write_text(_markdown(results, month_s, args.months, wall))
    with (args.out / "wear_runs.jsonl").open("w") as f:
        for r in results:
            f.write(json.dumps(r, sort_keys=True) + "\n")
    print((args.out / "wear.md").read_text())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
